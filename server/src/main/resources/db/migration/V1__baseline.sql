-- V1 기준선 (2026-11-18)
--
-- Flyway 도입 전까지 스키마는 spring.jpa.hibernate.ddl-auto=update가 만들고 고쳐 왔다. 이 파일은 그 결과인
-- 실제 로컬 DB를 pg_dump --schema-only로 떠서 정리한 것이다.
--
-- - 이미 테이블이 있는 기존 DB: spring.flyway.baseline-on-migrate로 "V1 적용됨" 표시만 하고 이 파일은 실행하지 않는다.
-- - 빈 DB(새로 클론, Testcontainers): 이 파일이 실행되어 같은 스키마를 만든다.
--
-- 실제 DB와 똑같이 맞추느라 일부러 남긴 점:
-- - scrap.failure_reason에는 CHECK 제약이 없다. PR #135에서 smallint를 varchar로 DB에서 직접 바꾸면서 빠졌다.
--   ddl-auto로 빈 DB를 새로 만들면 이 제약이 생겨서, 같은 엔티티인데 DB마다 스키마가 달랐다(Flyway 도입 이유).
-- - 외래키와 PK 외 인덱스는 없다. 필요해지면 새 버전 파일로 추가한다.

CREATE TABLE island (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    embedding text NOT NULL,
    name character varying(255) NOT NULL,
    x double precision,
    y double precision,
    CONSTRAINT island_pkey PRIMARY KEY (id)
);

CREATE TABLE scrap (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    content text,
    created_at timestamp(6) with time zone NOT NULL,
    embedding text,
    failure_reason character varying(255),
    fallback_level character varying(255) NOT NULL,
    island_id bigint,
    recommended_island_id bigint,
    source_type character varying(255) NOT NULL,
    summary text,
    title text,
    topic_id bigint,
    url text NOT NULL,
    user_context character varying(255),
    pending_ai_step character varying(255),
    CONSTRAINT scrap_pkey PRIMARY KEY (id),
    CONSTRAINT scrap_fallback_level_check CHECK (fallback_level IN
        ('DIRECT_EXTRACTION', 'OPEN_GRAPH_ONLY', 'SEARCH_SNIPPET', 'USER_INPUT', 'EXTRACTION_FAILED')),
    CONSTRAINT scrap_pending_ai_step_check CHECK (pending_ai_step IN
        ('SUMMARY', 'RECOMMENDATION')),
    CONSTRAINT scrap_source_type_check CHECK (source_type IN
        ('ARTICLE', 'NAVER_BLOG', 'NAMUWIKI', 'GITHUB', 'YOUTUBE', 'PDF', 'NOTION', 'UNKNOWN'))
);

CREATE TABLE topic (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    island_id bigint NOT NULL,
    name character varying(255) NOT NULL,
    CONSTRAINT topic_pkey PRIMARY KEY (id)
);
